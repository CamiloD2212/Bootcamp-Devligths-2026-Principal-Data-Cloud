SELECT category, SUM(price * quantity) AS ingreso
FROM sales
GROUP BY category
ORDER BY ingreso DESC
LIMIT 1;


SELECT product, AVG(price*quantity) AS ingresoPromedio
FROM sales
GROUP BY product;

SELECT product, SUM(quantity) AS total_vendido 
FROM sales 
GROUP BY product 
ORDER BY total_vendido DESC 
